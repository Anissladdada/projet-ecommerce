-- On supprime dans l'ordre inverse des dépendances
DROP TABLE IF EXISTS ligne_commande;
DROP TABLE IF EXISTS commande;
DROP TABLE IF EXISTS produit;
DROP TABLE IF EXISTS client;


-- Un client peut s'inscrire sans jamais commander : aucune contrainte
-- ne l'oblige à avoir une commande.
CREATE TABLE client (
    id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nom VARCHAR(100) NOT NULL,
    prenom VARCHAR(100) NOT NULL,
    email VARCHAR(150) NOT NULL UNIQUE,
    ville VARCHAR(100) NOT NULL,
    date_inscription DATE NOT NULL
);


-- Le prix est le prix actuel du catalogue. Le prix réellement payé
-- est stocké dans ligne_commande.
-- Le stock peut valoir 0 (produit en rupture), d'où >= 0 et non > 0.
CREATE TABLE produit (
    id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nom VARCHAR(150) NOT NULL,
    categorie VARCHAR(50) NOT NULL,
    prix DECIMAL(10,2) NOT NULL CHECK (prix >= 0),
    stock INTEGER NOT NULL CHECK (stock >= 0)
);


-- Relation 1-N avec client : la clé étrangère est du côté « plusieurs ».
CREATE TABLE commande (
    id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    client_id INTEGER NOT NULL REFERENCES client(id),
    date_commande DATE NOT NULL,
    statut VARCHAR(20) NOT NULL
        CHECK (statut IN ('payée', 'expédiée', 'livrée', 'annulée'))
);


-- Table de liaison entre commande et produit (relation N-N).
-- Elle porte la quantité et le prix unitaire payé, qui peut différer
-- du prix actuel du produit (promotions, historique).
CREATE TABLE ligne_commande (
    id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    commande_id INTEGER NOT NULL REFERENCES commande(id),
    produit_id INTEGER NOT NULL REFERENCES produit(id),
    quantite INTEGER NOT NULL CHECK (quantite > 0),
    prix_unitaire DECIMAL(10,2) NOT NULL CHECK (prix_unitaire >= 0)
);
